-- *********************************************************************
-- * WARNING - READ BEFORE RUNNING                                      *
-- *                                                                    *
-- * 1. This script is NON-DESTRUCTIVE by default. It only CREATES      *
-- *    schemas, tables, indexes, constraints and triggers.             *
-- *    Every object uses CREATE ... IF NOT EXISTS, so re-running is    *
-- *    safe and will NOT touch existing data.                          *
-- *                                                                    *
-- * 2. It does NOT drop, recreate or modify your existing             *
-- *    public.users table or any of its data.                          *
-- *                                                                    *
-- * 3. The only statements that replace existing objects are the       *
-- *    Trigger drops/recreates near the end (DROP TRIGGER IF EXISTS).  *
-- *    Those only affect triggers, never table data.                   *
-- *                                                                    *
-- * 4. A commented-out DESTRUCTIVE cleanup block is at the very end.   *
-- *    Do NOT uncomment it unless you truly want to delete data.       *
-- *********************************************************************
--
-- Schemas created:
--   product_service   -> categories, products
--   inventory_service -> inventory
--   order_service     -> orders, order_items
--
-- The existing User Service keeps using public.users (BIGINT identity).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. Schemas
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS product_service;
CREATE SCHEMA IF NOT EXISTS inventory_service;
CREATE SCHEMA IF NOT EXISTS order_service;


-- ---------------------------------------------------------------------
-- 1. Shared trigger function for updated_at
--    A single small function in public, reused by all tables.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- =====================================================================
-- 2. PRODUCT SERVICE
-- =====================================================================

-- 2.1 categories
CREATE TABLE IF NOT EXISTS product_service.categories (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    image_url   VARCHAR(255)
);

-- 2.2 products
--     category_id is NOT NULL and restricted: a category that still has
--     products cannot be deleted.
CREATE TABLE IF NOT EXISTS product_service.products (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand       VARCHAR(255),
    category_id BIGINT        NOT NULL,
    name        VARCHAR(255)  NOT NULL,
    price       NUMERIC(12,2) NOT NULL,
    description TEXT,
    unit        VARCHAR(50)   NOT NULL,
    image_url   VARCHAR(255),
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES product_service.categories (id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_products_price_non_negative
        CHECK (price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_products_category
    ON product_service.products (category_id);


-- =====================================================================
-- 3. INVENTORY SERVICE
-- =====================================================================

-- 3.1 inventory
--     product_id is a LOGICAL reference to product_service.products(id).
--     There is intentionally NO cross-schema foreign key.
CREATE TABLE IF NOT EXISTS inventory_service.inventory (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id  BIGINT      NOT NULL,
    product_id BIGINT      NOT NULL,
    quantity   INTEGER     NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_inventory_branch_product
        UNIQUE (branch_id, product_id),
    CONSTRAINT chk_inventory_quantity_non_negative
        CHECK (quantity >= 0)
);

CREATE INDEX IF NOT EXISTS idx_inventory_product
    ON inventory_service.inventory (product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_branch
    ON inventory_service.inventory (branch_id);


-- =====================================================================
-- 4. ORDER SERVICE
-- =====================================================================

-- 4.1 orders
--     customer_id is a LOGICAL reference to public.users(id).
--     branch_id is a LOGICAL reference (no branch table yet).
CREATE TABLE IF NOT EXISTS order_service.orders (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        NOT NULL,
    branch_id       BIGINT        NOT NULL,
    status          VARCHAR(50)   NOT NULL DEFAULT 'PENDING',
    address         TEXT,
    total_amount    NUMERIC(12,2) NOT NULL,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    cancelled_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_orders_total_non_negative
        CHECK (total_amount >= 0),
    CONSTRAINT chk_orders_discount_non_negative
        CHECK (discount_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_orders_customer ON order_service.orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_branch   ON order_service.orders (branch_id);
CREATE INDEX IF NOT EXISTS idx_orders_status   ON order_service.orders (status);

-- 4.2 order_items
--     order_id  -> internal FK (same service), CASCADE on delete so a
--                  deleted order removes its items and never orphans rows.
--     product_id -> LOGICAL reference to product_service.products(id), no FK.
--     product_name + unit_price are snapshots kept for historical accuracy.
CREATE TABLE IF NOT EXISTS order_service.order_items (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_name VARCHAR(255)  NOT NULL,
    quantity     INTEGER       NOT NULL,
    unit_price   NUMERIC(12,2) NOT NULL,
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES order_service.orders (id)
        ON DELETE CASCADE,
    CONSTRAINT chk_order_items_quantity_positive
        CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price_non_negative
        CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_order_items_order   ON order_service.order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_service.order_items (product_id);


-- =====================================================================
-- 5. updated_at triggers
--    (Replaces the trigger only - never touches data.)
-- =====================================================================
DROP TRIGGER IF EXISTS trg_products_updated_at ON product_service.products;
CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON product_service.products
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_inventory_updated_at ON inventory_service.inventory;
CREATE TRIGGER trg_inventory_updated_at
    BEFORE UPDATE ON inventory_service.inventory
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_orders_updated_at ON order_service.orders;
CREATE TRIGGER trg_orders_updated_at
    BEFORE UPDATE ON order_service.orders
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


